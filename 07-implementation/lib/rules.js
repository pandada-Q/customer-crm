'use strict';
// 《数据清洗规则手册》——脏数据清洗规则的唯一权威来源
//
// 用途：
//  1) 注入大模型（DeepSeek / OpenAI 兼容 llm）自由文本抽取 prompt，要求模型按规则还原脏数据；
//  2) 人工维护：每遇到一类新脏数据，在这里补一条规则，并同步在 clean.js 增加对应确定性实现（如可能）。
//
// 规则编号对应历史真实踩坑（详见工作日志）：
//  R1 公司名被逗号误拆（备份0812 秦岚「深圳市创新,科技有限公司」）→ 见 11 轮修复
//  R2 10 位短号被静默丢弃误报「缺少任何电话」（周杰 1391234567）→ 见 10 轮修复
//  R3 合作状态口语归一三枚举 → 四轮需求 2
//  R4 标签重复「客户/客户」→ 八轮需求 4
//  R5 手机号误入城市/邮箱等错位字段（秦岚 city=13699887766）→ 二轮整改 3
const RULE_SECTION = `
## 数据清洗规则（抽取与还原时必须遵守）
【公司名】
1. 公司名若被逗号误拆（例如源文「深圳市创新,科技有限公司」实为一家公司「深圳市创新科技有限公司」），必须合并还原成完整公司名：不得拆成两段入库、不得丢弃后半段、不得把后半段并入其他字段。
2. 公司后缀词（有限公司 / 科技 / 实业 / 贸易 / 集团 / 机械 等）不单独成行、不并入备注。
【电话】
3. 手机号固定 11 位且 1 开头（第 2 位 3-9）。遇到「1 开头但不足 11 位」的可疑号码（如 1391234567）：原样保留到 mobile 字段，并在 lowconf 中提示「手机号位数不足」，严禁丢弃、严禁自行补位、严禁改写为座机。
4. 座机必须含区号（0 开头，形如 0755-88881234）；不含区号的短号不当作座机。
【城市】
5. 口语城市归一为地级市（「深圳那边的」→「深圳」），不得携带「那边的 / 那边 / 附近」等口语词。
【合作状态】
6. cooperationStatus 只填三枚举：有效（已合作 / 合作中 / 长期合作 / 可做长期供应商）、待定（展会认识 / 可跟进 / 有意向 / 潜在 / 想合作）、暂停（暂停合作）；未提及时填空字符串 ''，不得自创其他取值。
【标签与字段】
7. 标签去重：同一联系人同一标签只保留一个（「客户,客户」→「客户」；「老客户」归一到「客户」）。
8. 纯数字 / 日期 / 电话号码不得写入城市、邮箱、备注等错位字段；发现错位须还原到正确字段。
【分流】
9. 非联系人事项（约饭提醒 / 回头找电话 / 记得通知等）抽入 todos，不得建成联系人。
10. 电话缺失或明显异常的联系人进入 lowconf（附原始片段），由人工补全；不确定时宁可低置信，不要编造或猜测补值。
11. 若整段文本是粘贴的表格行（含逗号分隔），同样先按上述规则还原被拆字段，再抽取。`;

module.exports = { RULE_SECTION };
